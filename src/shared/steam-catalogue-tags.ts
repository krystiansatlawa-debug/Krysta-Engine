export interface CatalogueSteamTag {
  id: number;
  english: string;
  label: string;
}

export function getSteamTagLabel(id: number, locale: string, fallback: string) {
  return locale.split(/[-_]/)[0].toLowerCase() === "pl"
    ? (polishTagNames[id] ?? fallback)
    : fallback;
}

export function getCatalogueSteamTags(
  metadata: Record<string, Record<string, number>>,
  locale: string
): CatalogueSteamTag[] {
  const language = locale.split(/[-_]/)[0].toLowerCase();
  const translated = new Map(
    Object.entries(metadata[language] ?? {}).map(([name, id]) => [
      id,
      name.trim(),
    ])
  );
  const tags = new Map<number, CatalogueSteamTag>();

  for (const [name, id] of Object.entries(
    metadata.en ?? metadata[language] ?? {}
  )) {
    const english = name.trim();
    if (!Number.isInteger(id) || id <= 0 || !english || tags.has(id)) continue;
    tags.set(id, {
      id,
      english,
      label: getSteamTagLabel(id, locale, translated.get(id) || english),
    });
  }

  return [...tags.values()].sort((a, b) =>
    a.label.localeCompare(b.label, language)
  );
}
